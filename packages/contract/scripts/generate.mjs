#!/usr/bin/env node
// Generates packages/contract/generated/ from the vendored contract (vendor/cwa/), so every package
// in the dashboard reads the specification's types, validators and data from one place and types
// none of it by hand (AGENTS.md, "Never invent vocabulary"):
//
//   types.ts            TypeScript types for the nine published schemas (json-schema-to-typescript)
//   validators.js/.d.ts standalone Ajv validators for the same schemas, compiled here so no browser
//                       ever compiles a schema: the dashboard's Content Security Policy forbids eval,
//                       and Ajv's runtime compiler needs it
//   data.ts             the contract files: reasons, requirements, the model, slot defaults and the
//                       assembler's scope, and the commit the lock pins
//   registry.ts         the conformance registry: profiles, route policies and their lock
//   implementations.ts  each implementation's published conformance report and source
//
// The data is split by module so the web app loads the registry and the reports only on the pages
// that show them.
//
//   node scripts/generate.mjs            write generated/
//   node scripts/generate.mjs --check    write nothing; fail, naming each stale file, when
//                                        generated/ differs from what the vendored contract gives

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

import { compile } from "json-schema-to-typescript"

import { standaloneValidators } from "./standalone.mjs"

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const VENDOR = join(ROOT, "vendor/cwa")
const OUT = join(ROOT, "generated")
const BASE = "https://contextwindowarchitecture.io/schema/"
const BANNER =
  "// Generated by packages/contract/scripts/generate.mjs from vendor/cwa/. Do not edit; run `pnpm generate`."

const readText = (path) => readFileSync(join(VENDOR, path), "utf8")
const read = (path) => JSON.parse(readText(path))
const json = (value) => JSON.stringify(value, null, 2)

const schemaFiles = readdirSync(join(VENDOR, "schema"))
  .filter((name) => name.endsWith(".schema.json"))
  .sort()
const schemas = schemaFiles.map((file) => ({ file, schema: read(`schema/${file}`) }))

// snapshot.schema.json → Snapshot, context_item.schema.json → ContextItem.
function typeName(file) {
  return file
    .replace(".schema.json", "")
    .split("_")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("")
}

// --- types ---------------------------------------------------------------------------------------

// One wrapper schema references every published schema, so a type shared through $ref is declared
// once. $refs resolve against the schemas' $id and are read from the vendored files, never fetched.
async function generateTypes() {
  const wrapper = {
    title: "CwaContract",
    description: "Every published schema; the wrapper exists only to generate the types once.",
    type: "object",
    additionalProperties: false,
    properties: Object.fromEntries(
      schemaFiles.map((file) => [file.replace(".schema.json", ""), { $ref: BASE + file }]),
    ),
  }
  const types = await compile(wrapper, "CwaContract", {
    bannerComment: BANNER,
    additionalProperties: false,
    strictIndexSignatures: true,
    ignoreMinAndMaxItems: true,
    format: true,
    style: { semi: false, singleQuote: false, printWidth: 100, trailingComma: "all" },
    $refOptions: {
      resolve: {
        http: false,
        vendored: {
          order: 1,
          canRead: (file) => file.url.startsWith(BASE),
          read: (file) => readText(`schema/${file.url.slice(BASE.length).split("#")[0]}`),
        },
      },
    },
  })
  // The schemas' titles name the declared types ("CWA assembly snapshot" → CWAAssemblySnapshot);
  // each also gets the name of its file, which is what the rest of the dashboard says.
  const aliases = schemas.map(({ file, schema }) => {
    const declared = schema.title.replace(/(^|\s)(\S)/g, (_, _space, c) => c.toUpperCase())
    if (!new RegExp(`^export (interface|type) ${declared}\\b`, "m").test(types)) {
      throw new Error(`json-schema-to-typescript declared no ${declared} for ${file}`)
    }
    return `export type ${typeName(file)} = ${declared}\n`
  })
  return `${types}\n// The published schemas by the names of their files.\n${aliases.join("")}`
}

// --- validators ----------------------------------------------------------------------------------

function generateValidators() {
  const names = Object.fromEntries(
    schemas.map(({ file, schema }) => [`validate${typeName(file)}`, schema.$id]),
  )
  const js = `${BANNER}\n${standaloneValidators(
    schemas.map(({ schema }) => schema),
    names,
  )}`

  const dts = [
    BANNER,
    'import type { ValidateFunction } from "ajv"',
    "",
    `import type { ${schemas.map(({ file }) => typeName(file)).join(", ")} } from "./types.ts"`,
    "",
    ...schemas.map(
      ({ file }) =>
        `/** Validates against the published ${file}, reporting every error. */\nexport declare const validate${typeName(file)}: ValidateFunction<${typeName(file)}>`,
    ),
    "",
  ].join("\n")
  return { js, dts }
}

// --- data ----------------------------------------------------------------------------------------

// conformance/README.md, Tokenizers and renderers: the ids listed before Optional are required, the
// ones under it optional. The README does not say which are tokenizers and which renderers, but every
// published case uses them (that section says so), so each id's kind is where the cases name it.
function components() {
  const readme = readFileSync(join(ROOT, "vendor/cwa/conformance/README.md"), "utf8")
  const start = readme.indexOf("\n## Tokenizers and renderers\n")
  const optional = readme.indexOf("\n### Optional\n", start)
  const end = readme.indexOf("\n## ", optional + 1)
  if (start < 0 || optional < 0 || end < 0) {
    throw new Error(
      "conformance/README.md: no Tokenizers and renderers section with an Optional list",
    )
  }
  const ids = (text) => [...text.matchAll(/^- `([a-z0-9-]+\/v[0-9]+)`/gm)].map((m) => m[1])
  const listed = [
    ...ids(readme.slice(start, optional)).map((id) => ({ id, required: true })),
    ...ids(readme.slice(optional, end)).map((id) => ({ id, required: false })),
  ]
  const cases = join(ROOT, "vendor/cwa/conformance/cases")
  const used = { tokenizers: new Set(), renderers: new Set() }
  for (const id of readdirSync(cases).sort()) {
    const snapshot = JSON.parse(readFileSync(join(cases, id, "snapshot.json"), "utf8"))
    used.tokenizers.add(snapshot.tokenizer)
    used.renderers.add(snapshot.renderer)
  }
  const kind = (entry) => {
    const asTokenizer = used.tokenizers.has(entry.id)
    const asRenderer = used.renderers.has(entry.id)
    if (asTokenizer === asRenderer) {
      throw new Error(
        `conformance/README.md: no case tells whether ${entry.id} is a tokenizer or a renderer`,
      )
    }
    return asTokenizer ? "tokenizers" : "renderers"
  }
  return {
    tokenizers: listed.filter((entry) => kind(entry) === "tokenizers"),
    renderers: listed.filter((entry) => kind(entry) === "renderers"),
  }
}

function generateData() {
  const lock = JSON.parse(readFileSync(join(ROOT, "vendor/cwa.lock.json"), "utf8"))
  const source = { repository: lock.repository, commit: lock.spec_commit, dirty: lock.dirty }
  return `${BANNER}

/** The repository and commit the vendored contract came from, and whether that checkout was dirty (vendor/cwa.lock.json). */
export const CONTRACT_SOURCE = ${json(source)} as const

/** contract/reasons.json: the exclusion and refusal codes, in the order R-21 ranks them. */
export const REASONS = ${json(read("contract/reasons.json"))} as const

/** contract/requirements.json: R-1 to R-26. */
export const REQUIREMENTS = ${json(read("contract/requirements.json"))} as const

/** contract/model.json: the planes, the slots, the item fields, the authority roles, the conflicts, the stages and the tests. */
export const MODEL = ${json(read("contract/model.json"))} as const

/** contract/slot-defaults.json: each slot's plane, authority, tier and policy-field defaults (R-3). */
export const SLOT_DEFAULTS = ${json(read("contract/slot-defaults.json"))} as const

/** contract/assembler-scope.json: whether each requirement is the assembler's, the boundary's or the application's. */
export const SCOPE = ${json(read("contract/assembler-scope.json"))} as const

/** conformance/README.md, Tokenizers and renderers: every published one, and whether every implementation must provide it. */
export const COMPONENTS = ${json(components())} as const

/** implementations/index.json: each implementation's id and label, without its report. */
export const IMPLEMENTATION_INDEX = ${json(read("implementations/index.json"))} as const

export type ReasonCode = (typeof REASONS)[number]["code"]
export type RequirementId = (typeof REQUIREMENTS)[number]["id"]
export type PlaneId = (typeof MODEL)["planes"][number]["id"]
export type SlotId = (typeof MODEL)["slots"][number]["id"]
export type ImplementationId = (typeof IMPLEMENTATION_INDEX)[number]["id"]
`
}

function generateRegistry() {
  const registry = {
    profiles: read("conformance/registry/profiles.json"),
    route_policies: read("conformance/registry/route-policies.json"),
    lock: read("conformance/registry/lock.json"),
  }
  return `${BANNER}
import type { Profile, RegistryLock, RoutePolicy } from "./types.ts"

/** conformance/registry/: the published profiles and route policies, and the lock that pins each by SHA-256. */
export const REGISTRY: {
  readonly profiles: readonly Profile[]
  readonly route_policies: readonly RoutePolicy[]
  readonly lock: RegistryLock
} = ${json(registry)}
`
}

function generateImplementations() {
  const index = read("implementations/index.json")
  const implementations = index.map(({ id, label }) => {
    const status = `implementations/${id}.status.json`
    return {
      id,
      label,
      ...read(`implementations/${id}.json`),
      ...(existsSync(join(VENDOR, status)) ? { status: read(status) } : {}),
    }
  })
  return `${BANNER}
import type { ConformanceReport } from "./types.ts"

/** Where an implementation's report came from: its repository, the commit it ran at, and that checkout's tags. */
export interface ImplementationSource {
  readonly repository: string
  readonly commit: string
  readonly dirty: boolean
  readonly tags: readonly string[]
}

/** implementations/: each implementation's published conformance report, the source it ran at, the
 * SHA-256 of each case by id as it ran, and, where the implementation publishes one, its requirement status. */
export interface Implementation {
  readonly id: string
  readonly label: string
  readonly source: ImplementationSource
  readonly report: ConformanceReport
  readonly cases_at_run: Readonly<Record<string, string>>
  readonly status?: {
    readonly source: ImplementationSource
    readonly requirements: readonly { readonly id: string; readonly status: string; readonly tests: number }[]
  }
}

/** implementations/index.json, in its order, with each implementation's files. */
export const IMPLEMENTATIONS: readonly Implementation[] = ${json(implementations)}
`
}

// --- main ----------------------------------------------------------------------------------------

const validators = generateValidators()
const outputs = {
  "types.ts": await generateTypes(),
  "validators.js": validators.js,
  "validators.d.ts": validators.dts,
  "data.ts": generateData(),
  "registry.ts": generateRegistry(),
  "implementations.ts": generateImplementations(),
}

if (process.argv.includes("--check")) {
  const stale = Object.entries(outputs)
    .filter(([name, text]) => {
      const path = join(OUT, name)
      return !existsSync(path) || readFileSync(path, "utf8") !== text
    })
    .map(([name]) => `generated/${name}`)
  if (stale.length > 0) {
    process.stderr.write(`generate: stale, run \`pnpm generate\`: ${stale.join(", ")}\n`)
    process.exit(1)
  }
} else {
  mkdirSync(OUT, { recursive: true })
  for (const [name, text] of Object.entries(outputs)) writeFileSync(join(OUT, name), text)
  process.stdout.write(`generated ${Object.keys(outputs).length} files into generated/\n`)
}
