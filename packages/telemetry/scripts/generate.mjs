#!/usr/bin/env node
// Generates packages/telemetry/generated/ from the envelope's schemas (schemas/*.v1.schema.json):
//
//   types.ts            TypeScript types (json-schema-to-typescript). A $ref to one of the contract's
//                       schemas becomes an import of the contract's generated type, so Snapshot and
//                       Trace are declared once, in @cwa-dashboard/contract.
//   validators.js/.d.ts standalone Ajv validators, compiled with the contract's schemas beside them
//                       so their $refs resolve, through the contract's shared generator.
//
//   node scripts/generate.mjs            write generated/
//   node scripts/generate.mjs --check    write nothing; fail, naming each stale file

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

import { standaloneValidators } from "@cwa-dashboard/contract/scripts/standalone.mjs"
import { compile } from "json-schema-to-typescript"

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const OUT = join(ROOT, "generated")
const CONTRACT = dirname(
  createRequire(import.meta.url).resolve("@cwa-dashboard/contract/package.json"),
)
const CONTRACT_BASE = "https://contextwindowarchitecture.io/schema/"
const BANNER =
  "// Generated by packages/telemetry/scripts/generate.mjs from schemas/. Do not edit; run `pnpm generate`."

const readJson = (path) => JSON.parse(readFileSync(path, "utf8"))

const contractSchemas = readdirSync(join(CONTRACT, "vendor/cwa/schema"))
  .filter((name) => name.endsWith(".schema.json"))
  .sort()
  .map((name) => readJson(join(CONTRACT, "vendor/cwa/schema", name)))

const schemas = readdirSync(join(ROOT, "schemas"))
  .sort()
  .flatMap((file) => {
    const match = /^([a-z0-9-]+)\.v([0-9]+)\.schema\.json$/.exec(file)
    if (!match) return []
    const [, kind, version] = match
    const name = `${kind
      .split("-")
      .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
      .join("")}V${version}`
    return [{ file, name, schema: readJson(join(ROOT, "schemas", file)) }]
  })

// --- types ---------------------------------------------------------------------------------------

// The contract's type for a schema file: snapshot.schema.json → Snapshot.
const contractType = (file) =>
  file
    .replace(".schema.json", "")
    .split("_")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("")

// Replaces every $ref into the contract's schemas with the matching contract type, as a tsType:
// a whole schema by its name, a property by indexed access (ContextItem["slot"]); and a $ref to
// the schema's own nonblank string with string.
function withContractTypes(node, used) {
  if (Array.isArray(node)) return node.map((child) => withContractTypes(child, used))
  if (node === null || typeof node !== "object") return node
  const ref = node.$ref
  // Every schema declares its own nonblank string; typed inline, the shared file declares no
  // Nonblank alias per schema.
  if (ref === "#/$defs/nonblank") {
    const rest = Object.fromEntries(Object.entries(node).filter(([key]) => key !== "$ref"))
    return { ...rest, tsType: "string" }
  }
  if (typeof ref === "string" && ref.startsWith(CONTRACT_BASE)) {
    const [file, pointer = ""] = ref.slice(CONTRACT_BASE.length).split("#")
    const type = contractType(file)
    used.add(type)
    const segments = pointer.split("/").filter(Boolean)
    let tsType = type
    for (let i = 0; i < segments.length; i += 2) {
      if (segments[i] !== "properties" || segments[i + 1] === undefined) {
        throw new Error(`cannot type the contract reference ${ref}`)
      }
      tsType += `[${JSON.stringify(segments[i + 1])}]`
    }
    const rest = Object.fromEntries(Object.entries(node).filter(([key]) => key !== "$ref"))
    return { ...rest, tsType }
  }
  return Object.fromEntries(
    Object.entries(node).map(([key, value]) => [key, withContractTypes(value, used)]),
  )
}

async function generateTypes() {
  const used = new Set()
  const parts = []
  for (const { name, schema } of schemas) {
    const typed = withContractTypes(schema, used)
    const declared = await compile(typed, name, {
      bannerComment: "",
      additionalProperties: false,
      strictIndexSignatures: true,
      ignoreMinAndMaxItems: true,
      format: true,
      style: { semi: false, singleQuote: false, printWidth: 100, trailingComma: "all" },
      $refOptions: { resolve: { http: false } },
    })
    const title = schema.title.replace(/(^|\s)(\S)/g, (_, _space, c) => c.toUpperCase())
    if (!new RegExp(`^export (interface|type) ${title}\\b`, "m").test(declared)) {
      throw new Error(`json-schema-to-typescript declared no ${title} for ${name}`)
    }
    parts.push(`${declared.trim()}\n\n/** ${schema.$id} */\nexport type ${name} = ${title}\n`)
  }
  const imports = [...used].sort().join(", ")
  return `${BANNER}\nimport type { ${imports} } from "@cwa-dashboard/contract/types"\n\n${parts.join("\n")}`
}

// --- validators ----------------------------------------------------------------------------------

function generateValidators() {
  const names = Object.fromEntries(
    schemas.map(({ name, schema }) => [`validate${name}`, schema.$id]),
  )
  const js = `${BANNER}\n${standaloneValidators(
    [...contractSchemas, ...schemas.map(({ schema }) => schema)],
    names,
  )}`
  const dts = [
    BANNER,
    'import type { ValidateFunction } from "ajv"',
    "",
    `import type { ${schemas.map(({ name }) => name).join(", ")} } from "./types.ts"`,
    "",
    ...schemas.map(
      ({ file, name }) =>
        `/** Validates against schemas/${file}, reporting every error. */\nexport declare const validate${name}: ValidateFunction<${name}>`,
    ),
    "",
  ].join("\n")
  return { js, dts }
}

// --- main ----------------------------------------------------------------------------------------

const validators = generateValidators()
const outputs = {
  "types.ts": await generateTypes(),
  "validators.js": validators.js,
  "validators.d.ts": validators.dts,
}

if (process.argv.includes("--check")) {
  const stale = Object.entries(outputs)
    .filter(([name, text]) => {
      const path = join(OUT, name)
      return !existsSync(path) || readFileSync(path, "utf8") !== text
    })
    .map(([name]) => `generated/${name}`)
  if (stale.length > 0) {
    process.stderr.write(`generate: stale, run \`pnpm generate\`: ${stale.join(", ")}\n`)
    process.exit(1)
  }
} else {
  mkdirSync(OUT, { recursive: true })
  for (const [name, text] of Object.entries(outputs)) writeFileSync(join(OUT, name), text)
  process.stdout.write(`generated ${Object.keys(outputs).length} files into generated/\n`)
}
